#!/usr/bin/env python3
"""The N-frame effect shaders' shared prelude, written into each file (2026-10-25). Each effect is an N:N filter on
PL_HOOK_FRAME_MIX: it binds a window of frames and works out, from rts_mix[], which slot is the current frame and how
far in time every other slot lies (the slots are not in time order: the window rule picks the nearest before and after
first, then greedily outward, ties to the earlier frame; at N:N a 7-frame window is [-3 .. +3], an 8-frame one
[-4 .. +3]).

    gen_effects.py          writes every *.body.glsl in this folder as <name>.glsl with the prelude for its window
"""
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent


def prelude(n, desc, extra=()):
    binds = "//!BIND HOOKED\n" + "".join(f"//!BIND FRAME{k}\n" for k in range(1, n)) + "".join(f"//!BIND {b}\n" for b in extra)
    fetch = "\n".join(f"    {'if' if k == 0 else 'else if'} (k == {k}) c = {'HOOKED' if k == 0 else f'FRAME{k}'}_tex(p).rgb;"
                      for k in range(n))
    return f"""//!HOOK FRAME_MIX
{binds}//!DESC {desc}
#define NW {n}
vec3 F(int k, vec2 p) {{
    vec3 c = vec3(0.0);
{fetch}
    return c;
}}
float T(int k) {{ return rts_mix[k]; }}                      // the slot's time relative to this output, in source frames
float L(vec3 c) {{ return dot(c, vec3(0.299, 0.587, 0.114)); }}
int NOW() {{ int b = 0; for (int k = 1; k < NW; k++) if (abs(T(k)) < abs(T(b))) b = k; return b; }}
"""


for body in sorted(HERE.glob("*.body.glsl")):
    text = body.read_text()
    head = re.search(r"^// WINDOW (\d+)\s*\n// DESC (.*)$", text, re.M)
    assert head, f"{body.name}: needs '// WINDOW n' and '// DESC ...' lines"
    n, desc = int(head.group(1)), head.group(2).strip()
    assert 2 <= n <= 8
    comment = text[:head.start()]
    extra = re.findall(r"^// BIND (\w+)$", text, re.M)
    tex = "".join(f"//!TEXTURE {name}\n//!SIZE {w} {h}\n//!FORMAT {fmt}\n//!STORAGE\n\n"
                  for name, w, h, fmt in re.findall(r"^// TEXTURE (\w+) (\d+) (\d+) (\w+)$", text, re.M))
    rest = re.sub(r"^// (BIND|TEXTURE) .*\n", "", text[head.end():], flags=re.M)
    pre = re.search(r"^// PREPASS BEGIN\n(.*?)^// PREPASS END\n", rest, re.M | re.S)   # a pass that must run first
    if pre:
        tex += pre.group(1) + "\n"
        rest = rest[:pre.start()] + rest[pre.end():]
    out = HERE / body.name.replace(".body.glsl", ".glsl")
    out.write_text(comment + "// (generated by gen_effects.py from " + body.name + "; edit the body)\n\n" + tex + prelude(n, desc, extra)
                   + rest)
    print("wrote", out.name, "window", n)
